type QRMarkProps = {
  className?: string;
  fg?: string;
  bg?: string;
};

export function QRMark({
  className = '',
  fg = '#07080b',
  bg = '#f3f4f6',
}: QRMarkProps) {
  const n = QR_MODULES.length;

  return (
    <svg
      viewBox={`0 0 ${n} ${n}`}
      className={className}
      shapeRendering="crispEdges"
      aria-hidden
    >
      <rect width={n} height={n} fill={bg} />
      {QR_MODULES.map((row, y) =>
        row.map((cell, x) =>
          cell ? (
            <rect key={`${y}-${x}`} x={x} y={y} width={1} height={1} fill={fg} />
          ) : null
        )
      )}
    </svg>
  );
}
